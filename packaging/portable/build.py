#!/usr/bin/env python3
"""Embed a locally tested Arch package in one Go executable (no publishing)."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile

root = Path(__file__).resolve().parents[2]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("package", type=Path)
parser.add_argument("output", type=Path)
args = parser.parse_args()
package = args.package.resolve(strict=True)
output = args.output.resolve()
if output.exists():
    parser.error("output already exists")
# The package is generated by makepkg, never populated from a checkout/state tree.
info = subprocess.check_output(["bsdtar", "-xOf", str(package), ".PKGINFO"], text=True)
fields = {}
for line in info.splitlines():
    key, sep, value = line.partition(" = ")
    if sep:
        fields.setdefault(key, []).append(value)
if fields.get("pkgname") != ["local-vpn-kde-native"] or fields.get("arch") != ["x86_64"]:
    parser.error("expected local-vpn-kde-native x86_64 package")
manifest = {
    "format": 1,
    "package": "application.pkg.tar.zst",
    "sha256": hashlib.sha256(package.read_bytes()).hexdigest(),
    "architecture": "amd64",
    "revision": fields["pkgver"][0],
    "dependencies": fields.get("depend", []),
}
output.parent.mkdir(parents=True, exist_ok=True)
with tempfile.TemporaryDirectory(prefix="vpnkit-portable-build-") as tmp:
    tmp = Path(tmp)
    shutil.copyfile(root / "cmd/vpnkit-portable/main.go", tmp / "main.go")
    (tmp / "payload").mkdir()
    shutil.copyfile(package, tmp / "payload/application.pkg.tar.zst")
    (tmp / "payload/manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    subprocess.run(["go", "build", "-trimpath", "-ldflags=-s -w", "-o", str(output), "main.go"],
                   cwd=tmp, env={**os.environ, "CGO_ENABLED": "0", "GOOS": "linux", "GOARCH": "amd64"}, check=True)
output.with_name(output.name + ".sha256").write_text(
    hashlib.sha256(output.read_bytes()).hexdigest() + "  " + output.name + "\n")
print(json.dumps(manifest, indent=2))
