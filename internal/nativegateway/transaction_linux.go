//go:build linux

package nativegateway

import (
	"context"
	"errors"
	"fmt"
	"os"
	"regexp"
	"strings"
)

// Runner executes one already-bounded command without invoking a shell. An
// error is an ambiguous result: the command may have mutated the host.
type Runner interface {
	Run(context.Context, Command) error
}

// JournalStore must make Save durable before returning success. Load must not
// silently replace malformed data, and Clear must durably remove the journal.
type JournalStore interface {
	Load(context.Context) (NetworkJournal, bool, error)
	Save(context.Context, NetworkJournal) error
	Clear(context.Context) error
}

// NetworkInspector is the authority for both complete planning snapshots and
// exact post-mutation state. Exact means the complete effect described by the
// corresponding PlanNetwork command (including selectors, protocol, table,
// addresses, nft ruleset, and sysctl value), not merely a name or marker.
// Namespace and veth identities must be immutable kernel identities.
type NetworkInspector interface {
	Snapshot(context.Context) (Snapshot, error)
	Inspect(context.Context, NetworkExpectation) (NetworkInspection, error)
}

const (
	NetworkJournalVersion       = 5
	legacyNetworkJournalVersion = 4
	MaxNetworkEffects           = 21
)

// EffectKind is a closed list. Journal data never contains executable commands.
type EffectKind uint8

const (
	EffectNamespace EffectKind = iota + 1
	EffectVeth
	EffectGuestMoved
	EffectUnreachableRule
	EffectHostAddress
	EffectGuestAddress
	EffectConnectedRoute
	EffectDefaultUplinkRoute
	EffectEgressRule
	EffectNFTTable
	EffectRouteLocalnet
	EffectIPv4Forwarding
	EffectDisableIPv6All
	EffectDisableIPv6Default
	EffectGuestDefaultRoute
	EffectHostUp
	EffectLoopbackUp
	EffectGuestUp
	EffectForwardEgress
	EffectForwardReturn
)

type EffectPhase uint8

const (
	EffectIntent EffectPhase = iota + 1
	EffectApplied
	EffectRemoving
	EffectRemoved
	// EffectRelinquished is valid only for global IPv4 forwarding. The
	// controller intentionally leaves that shared setting enabled on stop.
	EffectRelinquished
)

type NamespaceIdentity struct {
	Device uint64
	Inode  uint64
}

type VethIdentity struct {
	HostIfIndex  int
	GuestIfIndex int
}

type CreatedIdentity struct {
	Namespace NamespaceIdentity
	Veth      VethIdentity
}

type JournalEffect struct {
	Kind     EffectKind
	Phase    EffectPhase
	Identity CreatedIdentity
}

// NetworkJournal is deliberately fixed-size and versioned. InitialIPv4Forwarding
// determines whether the plan contains the global forwarding mutation.
type NetworkJournal struct {
	Version               uint16
	BootID                string
	Uplink                Uplink
	InitialIPv4Forwarding bool
	EffectCount           uint8
	Effects               [MaxNetworkEffects]JournalEffect
}

// NetworkExpectation is generated by Controller, never loaded from the
// journal. Inspectors must compare each effect with the exact state generated
// by PlanNetwork for Uplink and InitialIPv4Forwarding.
type NetworkExpectation struct {
	Uplink                Uplink
	InitialIPv4Forwarding bool
	EffectCount           uint8
	Effects               [MaxNetworkEffects]EffectKind
}

type ObservationState uint8

const (
	ObservationUnverifiable ObservationState = iota
	ObservationAbsent
	ObservationExact
	ObservationConflict
)

type EffectObservation struct {
	State    ObservationState
	Identity CreatedIdentity
}

type NetworkInspection struct {
	Effects [MaxNetworkEffects]EffectObservation
}

// ErrNetworkNeedsCleanup identifies missing owned state or an interrupted stop.
// Callers may retry only after a process-free namespace proof and successful Stop.
// It never authorizes deleting the journal or bypassing immutable identity checks.
var ErrNetworkNeedsCleanup = errors.New("native network requires verified cleanup")

type Controller struct {
	Runner    Runner
	Journal   JournalStore
	Inspector NetworkInspector
	bootID    func(context.Context) (string, error)
}

// Status reports whether a complete journal still matches every owned effect.
// It is read-only: incomplete or partially cleaned transactions are not ready,
// and malformed or replaced resources are errors rather than trusted state.
func (c Controller) Status(ctx context.Context) (bool, error) {
	if err := c.valid(); err != nil {
		return false, err
	}
	journal, exists, err := c.Journal.Load(ctx)
	if err != nil || !exists {
		return false, err
	}
	_, kinds, err := validateJournal(journal)
	if err != nil {
		return false, err
	}
	boot, err := c.currentBootID(ctx)
	if err != nil {
		return false, err
	}
	if journal.Version == NetworkJournalVersion && journal.BootID != boot {
		return false, nil
	}
	if int(journal.EffectCount) != len(kinds) {
		return false, nil
	}
	for n := 0; n < len(kinds); n++ {
		if journal.Effects[n].Phase != EffectApplied {
			return false, nil
		}
	}
	inspection, err := c.Inspector.Inspect(ctx, expectation(journal.Uplink, journal.InitialIPv4Forwarding, kinds))
	if err != nil {
		return false, err
	}
	for n, kind := range kinds {
		observed := inspection.Effects[n]
		if observed.State != ObservationExact {
			return false, fmt.Errorf("owned %s is not exact", effectName(kind))
		}
		if isIdentityEffect(kind) && journal.Effects[n].Identity != identityFor(kind, observed.Identity) {
			return false, fmt.Errorf("owned %s identity changed", effectName(kind))
		}
	}
	return true, nil
}

func (c Controller) Start(ctx context.Context, uplink Uplink) error {
	if err := c.valid(); err != nil {
		return err
	}
	journal, exists, err := c.Journal.Load(ctx)
	if err != nil {
		return fmt.Errorf("load network journal: %w", err)
	}
	boot, err := c.currentBootID(ctx)
	if err != nil {
		return err
	}
	var commands []Command
	var kinds []EffectKind
	if exists {
		commands, kinds, err = validateJournal(journal)
		if err != nil {
			return err
		}
		priorBoot := journal.Version == NetworkJournalVersion && journal.BootID != boot
		if priorBoot || journal.Version == legacyNetworkJournalVersion {
			absent, proofErr := c.exclusiveEffectsAbsent(ctx, journal, kinds)
			if proofErr != nil {
				return proofErr
			}
			if absent {
				// Do not clear the old durable ledger. The fresh plan below
				// replaces it atomically with current-boot intent before any
				// command, so interruption at either side remains recoverable.
				exists = false
			} else if priorBoot {
				return errors.New("prior-boot network journal has remaining or conflicting resources; refusing recovery")
			}
		}
	}
	if exists {
		if journal.Uplink != uplink {
			return errors.New("network journal belongs to a different uplink")
		}
		if err := c.reconcile(ctx, &journal, kinds); err != nil {
			return err
		}
		if journal.Version == legacyNetworkJournalVersion {
			// An intact legacy installation remains usable. Only stamp the
			// current epoch after the existing immutable-identity proof.
			journal.Version, journal.BootID = NetworkJournalVersion, boot
			if err := c.Journal.Save(ctx, journal); err != nil {
				return fmt.Errorf("migrate network journal boot identity: %w", err)
			}
		}
		complete := int(journal.EffectCount) == len(kinds)
		for i := 0; i < int(journal.EffectCount); i++ {
			if journal.Effects[i].Phase != EffectApplied {
				complete = false
			}
		}
		if complete {
			return nil
		}
	} else {
		snapshot, snapshotErr := c.Inspector.Snapshot(ctx)
		if snapshotErr != nil {
			return fmt.Errorf("inspect complete network snapshot: %w", snapshotErr)
		}
		commands, err = PlanNetwork(uplink, snapshot)
		if err != nil {
			return err
		}
		kinds, err = effectKinds(commands, snapshot.IPv4Forwarding)
		if err != nil {
			return err
		}
		// Shared forwarding is read afresh. A previous boot's initial
		// sysctl value is never restored or reused as current ownership.
		journal = NetworkJournal{Version: NetworkJournalVersion, BootID: boot, Uplink: uplink, InitialIPv4Forwarding: snapshot.IPv4Forwarding}
	}

	start := int(journal.EffectCount)
	if start > 0 && journal.Effects[start-1].Phase == EffectIntent {
		start--
	}
	for i := 0; i < start; i++ {
		if journal.Effects[i].Phase != EffectApplied {
			return fmt.Errorf("incomplete journal must be stopped before restarting: %w", ErrNetworkNeedsCleanup)
		}
	}
	for i := start; i < len(commands); i++ {
		if i == int(journal.EffectCount) {
			journal.Effects[i] = JournalEffect{Kind: kinds[i], Phase: EffectIntent}
			journal.EffectCount = uint8(i + 1)
			if err := c.Journal.Save(ctx, journal); err != nil {
				return fmt.Errorf("save intent for %s: %w", effectName(kinds[i]), err)
			}
		}

		runErr := c.Runner.Run(ctx, cloneCommand(commands[i]))
		reconcileCtx := ctx
		if runErr != nil || ctx.Err() != nil {
			reconcileCtx = context.WithoutCancel(ctx)
		}
		inspection, inspectErr := c.Inspector.Inspect(reconcileCtx, expectation(journal.Uplink, journal.InitialIPv4Forwarding, kinds))
		if inspectErr != nil {
			return errors.Join(runErr, fmt.Errorf("inspect ambiguous %s result: %w", effectName(kinds[i]), inspectErr))
		}
		observation := inspection.Effects[i]
		if observation.State == ObservationExact {
			journal.Effects[i].Identity = identityFor(kinds[i], observation.Identity)
			journal.Effects[i].Phase = EffectApplied
			if err := c.Journal.Save(reconcileCtx, journal); err != nil {
				return errors.Join(runErr, fmt.Errorf("record applied %s: %w", effectName(kinds[i]), err))
			}
		} else if runErr == nil {
			return fmt.Errorf("%s command succeeded but exact state is %s", effectName(kinds[i]), observationName(observation.State))
		}
		if runErr != nil {
			if observation.State != ObservationAbsent && observation.State != ObservationExact {
				return fmt.Errorf("%s failed with ambiguous, unsafe state %s: %w", effectName(kinds[i]), observationName(observation.State), runErr)
			}
			cleanupErr := c.stopJournal(reconcileCtx, &journal, kinds)
			return errors.Join(fmt.Errorf("apply %s: %w", effectName(kinds[i]), runErr), cleanupErr)
		}
	}
	return nil
}

func (c Controller) Stop(ctx context.Context) error {
	if err := c.valid(); err != nil {
		return err
	}
	journal, exists, err := c.Journal.Load(ctx)
	if err != nil {
		return fmt.Errorf("load network journal: %w", err)
	}
	if !exists {
		return nil
	}
	_, kinds, err := validateJournal(journal)
	if err != nil {
		return err
	}
	boot, err := c.currentBootID(ctx)
	if err != nil {
		return err
	}
	if journal.Version == NetworkJournalVersion && journal.BootID != boot {
		absent, err := c.exclusiveEffectsAbsent(ctx, journal, kinds)
		if err != nil {
			return err
		}
		if !absent {
			return errors.New("prior-boot network journal has remaining or conflicting resources; refusing cleanup")
		}
		return c.Journal.Clear(ctx)
	}
	if err := c.preflightStop(ctx, journal, kinds); err != nil {
		return err
	}
	return c.stopJournal(ctx, &journal, kinds)
}

var bootIDPattern = regexp.MustCompile(`^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$`)

func (c Controller) currentBootID(ctx context.Context) (string, error) {
	if err := ctx.Err(); err != nil {
		return "", err
	}
	var boot string
	var err error
	if c.bootID != nil {
		boot, err = c.bootID(ctx)
	} else {
		var data []byte
		data, err = os.ReadFile("/proc/sys/kernel/random/boot_id")
		boot = strings.TrimSpace(string(data))
	}
	if err != nil || !bootIDPattern.MatchString(boot) {
		return "", errors.New("current kernel boot identity unavailable or invalid")
	}
	return boot, nil
}

// Retiring a ledger is permitted only when every exclusive effect in its
// complete plan is absent, including effects beyond a crash-truncated prefix.
// Global IPv4 forwarding is shared and cannot attest ownership across boots.
func (c Controller) exclusiveEffectsAbsent(ctx context.Context, journal NetworkJournal, kinds []EffectKind) (bool, error) {
	inspection, err := c.Inspector.Inspect(ctx, expectation(journal.Uplink, journal.InitialIPv4Forwarding, kinds))
	if err != nil {
		return false, fmt.Errorf("inspect obsolete network journal: %w", err)
	}
	for i, kind := range kinds {
		if kind == EffectIPv4Forwarding {
			continue
		}
		if inspection.Effects[i].State != ObservationAbsent {
			return false, nil
		}
	}
	return true, nil
}

func (c Controller) valid() error {
	if c.Runner == nil || c.Journal == nil || c.Inspector == nil {
		return errors.New("network controller dependencies are required")
	}
	return nil
}

func (c Controller) reconcile(ctx context.Context, journal *NetworkJournal, kinds []EffectKind) error {
	inspection, err := c.Inspector.Inspect(ctx, expectation(journal.Uplink, journal.InitialIPv4Forwarding, kinds))
	if err != nil {
		return fmt.Errorf("inspect journaled network: %w", err)
	}
	changed := false
	for i := 0; i < int(journal.EffectCount); i++ {
		record := &journal.Effects[i]
		observation := inspection.Effects[i]
		switch record.Phase {
		case EffectRemoved:
			if observation.State != ObservationAbsent {
				return fmt.Errorf("removed %s is no longer absent", effectName(record.Kind))
			}
		case EffectRelinquished:
			if record.Kind != EffectIPv4Forwarding || (observation.State != ObservationAbsent && observation.State != ObservationExact) {
				return fmt.Errorf("invalid relinquished state for %s", effectName(record.Kind))
			}
		case EffectIntent, EffectApplied, EffectRemoving:
			if observation.State == ObservationConflict || observation.State == ObservationUnverifiable {
				return fmt.Errorf("journaled %s is %s", effectName(record.Kind), observationName(observation.State))
			}
			if observation.State == ObservationAbsent {
				if record.Phase == EffectIntent {
					continue
				}
				return fmt.Errorf("applied %s is absent: %w", effectName(record.Kind), ErrNetworkNeedsCleanup)
			}
			observedIdentity := identityFor(record.Kind, observation.Identity)
			if !identityEmpty(record.Identity) && record.Identity != observedIdentity {
				return fmt.Errorf("journaled %s identity changed", effectName(record.Kind))
			}
			if isIdentityEffect(record.Kind) && identityEmpty(observedIdentity) {
				return fmt.Errorf("journaled %s has no verifiable immutable identity", effectName(record.Kind))
			}
			if identityEmpty(record.Identity) {
				record.Identity = observedIdentity
			}
			record.Phase = EffectApplied
			changed = true
		default:
			return fmt.Errorf("invalid phase for %s", effectName(record.Kind))
		}
	}
	if changed {
		if err := c.Journal.Save(ctx, *journal); err != nil {
			return fmt.Errorf("save reconciled journal: %w", err)
		}
	}
	return nil
}

func (c Controller) preflightStop(ctx context.Context, journal NetworkJournal, kinds []EffectKind) error {
	inspection, err := c.Inspector.Inspect(ctx, expectation(journal.Uplink, journal.InitialIPv4Forwarding, kinds))
	if err != nil {
		return fmt.Errorf("inspect before cleanup: %w", err)
	}
	for i := 0; i < int(journal.EffectCount); i++ {
		record := journal.Effects[i]
		observation := inspection.Effects[i]
		if record.Phase == EffectRemoved {
			if observation.State != ObservationAbsent {
				return fmt.Errorf("removed %s is no longer absent", effectName(record.Kind))
			}
			continue
		}
		if record.Phase == EffectRelinquished {
			if record.Kind != EffectIPv4Forwarding || (observation.State != ObservationAbsent && observation.State != ObservationExact) {
				return fmt.Errorf("invalid relinquished state for %s", effectName(record.Kind))
			}
			continue
		}
		if observation.State != ObservationAbsent && observation.State != ObservationExact {
			return fmt.Errorf("refusing cleanup: %s is %s", effectName(record.Kind), observationName(observation.State))
		}
		if observation.State == ObservationExact && !identityEmpty(record.Identity) && record.Identity != identityFor(record.Kind, observation.Identity) {
			return fmt.Errorf("refusing cleanup: %s identity changed", effectName(record.Kind))
		}
		if observation.State == ObservationExact && isIdentityEffect(record.Kind) && identityEmpty(identityFor(record.Kind, observation.Identity)) {
			return fmt.Errorf("refusing cleanup: %s identity is unverifiable", effectName(record.Kind))
		}
	}
	return nil
}

func (c Controller) stopJournal(ctx context.Context, journal *NetworkJournal, kinds []EffectKind) error {
	expect := expectation(journal.Uplink, journal.InitialIPv4Forwarding, kinds)
	for i := int(journal.EffectCount) - 1; i >= 0; i-- {
		record := &journal.Effects[i]
		if record.Phase == EffectRemoved || record.Phase == EffectRelinquished {
			continue
		}
		inspection, err := c.Inspector.Inspect(ctx, expect)
		if err != nil {
			return fmt.Errorf("inspect before removing %s: %w", effectName(record.Kind), err)
		}
		observation := inspection.Effects[i]
		if observation.State == ObservationAbsent {
			record.Phase = EffectRemoved
			if err := c.Journal.Save(ctx, *journal); err != nil {
				return fmt.Errorf("record absent %s: %w", effectName(record.Kind), err)
			}
			continue
		}
		if observation.State != ObservationExact {
			return fmt.Errorf("refusing to remove %s in state %s", effectName(record.Kind), observationName(observation.State))
		}
		observedIdentity := identityFor(record.Kind, observation.Identity)
		if isIdentityEffect(record.Kind) {
			if identityEmpty(observedIdentity) || (!identityEmpty(record.Identity) && record.Identity != observedIdentity) {
				return fmt.Errorf("refusing to remove %s with unproven identity", effectName(record.Kind))
			}
			if identityEmpty(record.Identity) {
				record.Identity = observedIdentity
				record.Phase = EffectApplied
				if err := c.Journal.Save(ctx, *journal); err != nil {
					return fmt.Errorf("record recovered identity for %s: %w", effectName(record.Kind), err)
				}
			}
		}
		if record.Kind == EffectUnreachableRule && !guestPathsDisabled(inspection, kinds) {
			return errors.New("refusing to remove source-unreachable protection while guest paths are enabled")
		}
		record.Phase = EffectRemoving
		if err := c.Journal.Save(ctx, *journal); err != nil {
			return fmt.Errorf("save removal intent for %s: %w", effectName(record.Kind), err)
		}
		command, run := reverseCommand(record.Kind, journal.Uplink)
		if !run {
			if record.Kind == EffectIPv4Forwarding {
				record.Phase = EffectRelinquished
				if err := c.Journal.Save(context.WithoutCancel(ctx), *journal); err != nil {
					return fmt.Errorf("record relinquished %s: %w", effectName(record.Kind), err)
				}
			}
			continue
		}
		runErr := c.Runner.Run(ctx, command)
		post, inspectErr := c.Inspector.Inspect(context.WithoutCancel(ctx), expect)
		if inspectErr != nil {
			return errors.Join(runErr, fmt.Errorf("inspect removal of %s: %w", effectName(record.Kind), inspectErr))
		}
		if post.Effects[i].State != ObservationAbsent {
			return errors.Join(runErr, fmt.Errorf("removal of %s left state %s", effectName(record.Kind), observationName(post.Effects[i].State)))
		}
		record.Phase = EffectRemoved
		if err := c.Journal.Save(context.WithoutCancel(ctx), *journal); err != nil {
			return fmt.Errorf("record removed %s: %w", effectName(record.Kind), err)
		}
	}
	final, err := c.Inspector.Inspect(context.WithoutCancel(ctx), expect)
	if err != nil {
		return fmt.Errorf("inspect completed cleanup: %w", err)
	}
	for i := 0; i < int(journal.EffectCount); i++ {
		record := &journal.Effects[i]
		if record.Phase == EffectRelinquished {
			continue
		}
		if final.Effects[i].State != ObservationAbsent {
			return fmt.Errorf("cleanup left %s in state %s", effectName(record.Kind), observationName(final.Effects[i].State))
		}
		if record.Phase != EffectRemoved {
			record.Phase = EffectRemoved
			if err := c.Journal.Save(context.WithoutCancel(ctx), *journal); err != nil {
				return fmt.Errorf("record cascaded removal of %s: %w", effectName(record.Kind), err)
			}
		}
	}
	if err := c.Journal.Clear(context.WithoutCancel(ctx)); err != nil {
		return fmt.Errorf("clear network journal: %w", err)
	}
	return nil
}

func validateJournal(journal NetworkJournal) ([]Command, []EffectKind, error) {
	if journal.Version != NetworkJournalVersion && journal.Version != legacyNetworkJournalVersion {
		return nil, nil, errors.New("unsupported or tampered network journal version")
	}
	if (journal.Version == NetworkJournalVersion && !bootIDPattern.MatchString(journal.BootID)) ||
		(journal.Version == legacyNetworkJournalVersion && journal.BootID != "") {
		return nil, nil, errors.New("invalid network journal boot identity")
	}
	commands, err := PlanNetwork(journal.Uplink, Snapshot{IPv4Forwarding: journal.InitialIPv4Forwarding})
	if err != nil {
		return nil, nil, fmt.Errorf("invalid network journal uplink: %w", err)
	}
	kinds, err := effectKinds(commands, journal.InitialIPv4Forwarding)
	if err != nil {
		return nil, nil, err
	}
	if journal.EffectCount == 0 || journal.EffectCount > uint8(len(kinds)) {
		return nil, nil, errors.New("network journal effect count is out of bounds")
	}
	cleanupStarted := false
	for i := 0; i < int(journal.EffectCount); i++ {
		r := journal.Effects[i]
		if r.Kind != kinds[i] || r.Phase < EffectIntent || r.Phase > EffectRelinquished || (r.Phase == EffectRelinquished && r.Kind != EffectIPv4Forwarding) {
			return nil, nil, errors.New("network journal contains invalid effect data")
		}
		if !identityValidFor(r.Kind, r.Identity) {
			return nil, nil, errors.New("network journal contains invalid identity data")
		}
		if (r.Phase == EffectApplied || r.Phase == EffectRemoving) && isIdentityEffect(r.Kind) && identityEmpty(r.Identity) {
			return nil, nil, errors.New("network journal omits an applied immutable identity")
		}
		if r.Phase == EffectIntent && i != int(journal.EffectCount)-1 {
			return nil, nil, errors.New("network journal contains an out-of-order intent")
		}
		isCleanup := r.Phase == EffectRemoving || r.Phase == EffectRemoved || r.Phase == EffectRelinquished
		if isCleanup {
			cleanupStarted = true
		} else if cleanupStarted {
			return nil, nil, errors.New("network journal cleanup phases are out of order")
		}
	}
	for i := int(journal.EffectCount); i < MaxNetworkEffects; i++ {
		if journal.Effects[i] != (JournalEffect{}) {
			return nil, nil, errors.New("network journal contains trailing effect data")
		}
	}
	return commands, kinds, nil
}

func effectKinds(commands []Command, forwardingInitiallyEnabled bool) ([]EffectKind, error) {
	kinds := []EffectKind{EffectNamespace, EffectVeth, EffectGuestMoved, EffectUnreachableRule, EffectHostAddress, EffectGuestAddress, EffectConnectedRoute, EffectDefaultUplinkRoute, EffectEgressRule, EffectNFTTable, EffectForwardEgress, EffectForwardReturn, EffectRouteLocalnet}
	if !forwardingInitiallyEnabled {
		kinds = append(kinds, EffectIPv4Forwarding)
	}
	kinds = append(kinds, EffectDisableIPv6All, EffectDisableIPv6Default, EffectHostUp, EffectLoopbackUp, EffectGuestUp, EffectGuestDefaultRoute)
	if len(commands) != len(kinds) || len(kinds) > MaxNetworkEffects {
		return nil, errors.New("PlanNetwork changed without a transaction effect mapping")
	}
	return kinds, nil
}

func expectation(uplink Uplink, forwarding bool, kinds []EffectKind) NetworkExpectation {
	e := NetworkExpectation{Uplink: uplink, InitialIPv4Forwarding: forwarding, EffectCount: uint8(len(kinds))}
	copy(e.Effects[:], kinds)
	return e
}

func identityFor(kind EffectKind, identity CreatedIdentity) CreatedIdentity {
	switch kind {
	case EffectNamespace:
		return CreatedIdentity{Namespace: identity.Namespace}
	case EffectVeth:
		return CreatedIdentity{Veth: identity.Veth}
	case EffectGuestMoved:
		return CreatedIdentity{Namespace: identity.Namespace, Veth: identity.Veth}
	default:
		return CreatedIdentity{}
	}
}

func isIdentityEffect(kind EffectKind) bool {
	return kind == EffectNamespace || kind == EffectVeth || kind == EffectGuestMoved
}

func identityEmpty(identity CreatedIdentity) bool { return identity == (CreatedIdentity{}) }

func identityValidFor(kind EffectKind, identity CreatedIdentity) bool {
	if identityEmpty(identity) {
		return true
	}
	switch kind {
	case EffectNamespace:
		return identity.Namespace.Device != 0 && identity.Namespace.Inode != 0 && identity.Veth == (VethIdentity{})
	case EffectVeth:
		return identity.Namespace == (NamespaceIdentity{}) && identity.Veth.HostIfIndex > 0 && identity.Veth.GuestIfIndex > 0
	case EffectGuestMoved:
		return identity.Namespace.Device != 0 && identity.Namespace.Inode != 0 && identity.Veth.HostIfIndex > 0 && identity.Veth.GuestIfIndex > 0
	default:
		return false
	}
}

func guestPathsDisabled(inspection NetworkInspection, kinds []EffectKind) bool {
	for i, kind := range kinds {
		switch kind {
		case EffectEgressRule, EffectGuestDefaultRoute, EffectHostUp, EffectGuestUp:
			if inspection.Effects[i].State != ObservationAbsent {
				return false
			}
		}
	}
	return true
}

// reverseCommand is the only teardown command generator. Global IPv4
// forwarding is intentionally never reset: a boolean sysctl has no ownership
// token, so disabling it could break a service that began relying on it after
// Start. Namespace/interface-scoped sysctls disappear with owned resources.
func reverseCommand(kind EffectKind, uplink Uplink) (Command, bool) {
	switch kind {
	case EffectGuestUp:
		return Command{Program: "ip", Args: []string{"-n", Namespace, "link", "set", GuestInterface, "down"}}, true
	case EffectLoopbackUp:
		return Command{Program: "ip", Args: []string{"-n", Namespace, "link", "set", "lo", "down"}}, true
	case EffectHostUp:
		return Command{Program: "ip", Args: []string{"link", "set", HostInterface, "down"}}, true
	case EffectGuestDefaultRoute:
		return Command{Program: "ip", Args: []string{"-n", Namespace, "route", "del", "default", "via", HostAddress, "dev", GuestInterface}}, true
	case EffectForwardEgress:
		return forwardCompatibilityCommand(uplink.Interface, false, "-D"), true
	case EffectForwardReturn:
		return forwardCompatibilityCommand(uplink.Interface, true, "-D"), true
	case EffectNFTTable:
		return Command{Program: "nft", Args: []string{"delete", "table", NFTFamily, NFTTable}}, true
	case EffectEgressRule:
		return Command{Program: "ip", Args: []string{"rule", "del", "from", GuestAddress + "/32", "iif", HostInterface, "priority", fmt.Sprint(EgressRulePriority), "protocol", fmt.Sprint(RouteProtocol), "lookup", fmt.Sprint(RoutingTable)}}, true
	case EffectDefaultUplinkRoute:
		return Command{Program: "ip", Args: []string{"route", "del", "default", "via", uplink.Gateway, "dev", uplink.Interface, "table", fmt.Sprint(RoutingTable), "protocol", fmt.Sprint(RouteProtocol)}}, true
	case EffectConnectedRoute:
		address, prefix, _, _ := validateUplink(uplink)
		return Command{Program: "ip", Args: []string{"route", "del", prefix.String(), "dev", uplink.Interface, "src", address.String(), "table", fmt.Sprint(RoutingTable), "protocol", fmt.Sprint(RouteProtocol), "scope", "link"}}, true
	case EffectGuestAddress:
		return Command{Program: "ip", Args: []string{"-n", Namespace, "addr", "del", GuestAddress + "/30", "dev", GuestInterface}}, true
	case EffectHostAddress:
		return Command{Program: "ip", Args: []string{"addr", "del", HostAddress + "/30", "dev", HostInterface}}, true
	case EffectUnreachableRule:
		return Command{Program: "ip", Args: []string{"rule", "del", "from", GuestAddress + "/32", "priority", fmt.Sprint(UnreachableRulePriority), "protocol", fmt.Sprint(RouteProtocol), "unreachable"}}, true
	case EffectVeth:
		return Command{Program: "ip", Args: []string{"link", "del", HostInterface}}, true
	case EffectNamespace:
		return Command{Program: "ip", Args: []string{"netns", "del", Namespace}}, true
	default:
		return Command{}, false
	}
}

func cloneCommand(command Command) Command {
	command.Args = append([]string(nil), command.Args...)
	return command
}

func effectName(kind EffectKind) string { return fmt.Sprintf("effect-%d", kind) }

func observationName(state ObservationState) string {
	switch state {
	case ObservationAbsent:
		return "absent"
	case ObservationExact:
		return "exact"
	case ObservationConflict:
		return "conflicting"
	default:
		return "unverifiable"
	}
}
